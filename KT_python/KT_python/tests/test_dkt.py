"""Tests for knowledge_tracer.dkt.

The parity tests mirror DktModelTest on the Java side: the numpy forward pass must
reproduce the Python reference fixture (backend/src/test/resources/dkt/fixture-*.json,
generated by model/dkt/make_fixture.py) to 1e-9. The predictor tests run the REAL
exported model (model/artifacts/dkt/dkt-model.json) against the mini catalog.
"""
from __future__ import annotations

import json
import math
import uuid
from pathlib import Path

import pytest
from sqlalchemy import select

from knowledge_tracer.dkt import (DktModel, LstmDktPredictor,
                                  UnavailableDktPredictor, build_predictor)
from knowledge_tracer.domain import (Concept, Learner, Problem, ProblemConcept,
                                     StaticDifficulty)
from tests.conftest import event_request

ROOT = Path(__file__).resolve().parents[2]
ARTIFACT = ROOT / "model" / "artifacts" / "dkt" / "dkt-model.json"
FIXTURE_MODEL = ROOT / "backend" / "src" / "test" / "resources" / "dkt" / "fixture-model.json"
FIXTURE_EXPECTED = ROOT / "backend" / "src" / "test" / "resources" / "dkt" / "fixture-expected.json"

needs_artifact = pytest.mark.skipif(not ARTIFACT.exists(), reason="exported DKT model not present")
needs_fixture = pytest.mark.skipif(not (FIXTURE_MODEL.exists() and FIXTURE_EXPECTED.exists()),
                                   reason="DKT parity fixture not present")


def _load_fixture_model() -> DktModel:
    return DktModel.from_json(json.loads(FIXTURE_MODEL.read_text(encoding="utf-8")))


def _enable_dkt(settings) -> None:
    settings.dkt.enabled = True
    settings.dkt.model_path = str(ARTIFACT)


def _problem(session, key: str) -> Problem:
    return session.scalar(select(Problem).where(Problem.problem_key == key))


def _learner_id(session, external_ref: str) -> uuid.UUID:
    return session.scalar(select(Learner).where(Learner.external_ref == external_ref)).id


# --- DktModel: parity with the Python reference (DktModelTest) ---------------------


@needs_fixture
def test_forward_pass_matches_python_reference_fixture():
    """Port of DktModelTest.javaForwardPassMatchesPythonReference (1e-9 tolerance)."""
    model = _load_fixture_model()
    steps = json.loads(FIXTURE_EXPECTED.read_text(encoding="utf-8"))["steps"]
    assert len(model.concepts) == 25

    state = model.initial_state()
    for step in steps:
        w, d = step["weights"], step["scaledDifficulty"]
        predicted = model.predict(model.concept_logits(state), w, d,
                                  step["attempted"], step["problemKey"])
        assert predicted == pytest.approx(step["predictionBefore"], abs=1e-9)

        state = model.step(state, model.input(w, step["correct"], d, step["assisted"]))
        logits = model.concept_logits(state)
        for k, expected in enumerate(step["masteryAfter"]):
            assert model.mastery(logits, k) == pytest.approx(expected, abs=1e-9)


@needs_fixture
def test_input_encoding_splits_correct_and_incorrect_evidence():
    """Port of DktModelTest.inputEncodingSplitsCorrectAndIncorrectEvidence."""
    model = _load_fixture_model()
    w = [0.0] * 25
    w[0] = 1.0
    w[3] = 0.5
    ok = model.input(w, True, 0.25, False)
    bad = model.input(w, False, 0.25, True)
    assert len(ok) == 52
    assert ok[0] == 1.0
    assert ok[25] == 0.0
    assert bad[25] == 1.0
    assert bad[28] == 0.5
    assert ok[50] == 0.25
    assert ok[51] == 0.0
    assert bad[51] == 1.0
    assert DktModel.scaled_difficulty(7.0) == 1.0


@needs_fixture
def test_rejects_wrong_format_and_shapes():
    """Port of DktModelTest.rejectsWrongFormatAndShapes (ValueError ~ IllegalArgumentException)."""
    doc = json.loads(FIXTURE_MODEL.read_text(encoding="utf-8"))
    with pytest.raises(ValueError, match="format"):
        DktModel.from_json(dict(doc, format="x"))
    with pytest.raises(ValueError, match="lstm.weight_ih"):
        DktModel.from_json(dict(doc, hiddenSize=5))


# --- DktModel: the real exported artifact ------------------------------------------


@needs_artifact
def test_real_model_loads_with_sane_metadata():
    model = DktModel.load(ARTIFACT)
    assert len(model.concepts) == 25
    assert model.hidden_size == 64
    assert model.max_sequence_length == 200
    assert model.trained_on == "synthetic"
    assert model.created_at
    assert model.test_auc is not None and 0.5 < model.test_auc <= 1.0
    assert model.concept_index("ARRAYS") == 0
    assert model.concept_index("NO_SUCH_CONCEPT") is None


@needs_artifact
def test_outputs_stay_finite_and_in_unit_interval():
    model = DktModel.load(ARTIFACT)
    k = len(model.concepts)
    state = model.initial_state()
    for t in range(60):
        w = [0.0] * k
        w[t % k] = 1.0
        w[(7 * t + 3) % k] = 0.5
        d = ((t % 9) - 4) / 2.0
        p = model.predict(model.concept_logits(state), w, d, t % 3 == 0, "LC999999")
        assert math.isfinite(p) and 0.0 <= p <= 1.0
        state = model.step(state, model.input(w, t % 2 == 0, d, t % 4 == 0))
        logits = model.concept_logits(state)
        assert all(math.isfinite(v) for v in logits)
        assert all(0.0 <= model.mastery(logits, i) <= 1.0 for i in range(k))


# --- LstmDktPredictor over the mini catalog, with the real model -------------------


@needs_artifact
class TestLstmDktPredictor:
    def test_build_predictor_returns_lstm_when_enabled_and_loadable(
            self, session, settings, mini_catalog):
        _enable_dkt(settings)
        predictor = build_predictor(session, settings)
        assert isinstance(predictor, LstmDktPredictor)
        assert predictor.available()
        status = predictor.status()
        assert status.startswith(
            "ENABLED (LSTM kt-dkt-v1, K=25, H=64, trained on synthetic data ")
        assert ", test AUC " in status
        assert status.endswith("; dkt-model.json)")

    def test_snapshot_without_events_is_the_zero_state(self, session, settings, mini_catalog):
        _enable_dkt(settings)
        predictor = build_predictor(session, settings)
        snap = predictor.snapshot(uuid.uuid4())
        assert snap is not None
        assert snap.events_replayed == 0
        mastery = snap.mastery()
        assert list(mastery.keys()) == list(predictor.model.concepts)
        assert all(0.0 <= v <= 1.0 for v in mastery.values())
        p = snap.predict_success(_problem(session, "LC_E1"))
        assert p is not None and 0.0 <= p <= 1.0

    def test_snapshot_changes_after_events(self, session, settings, mini_catalog, services):
        _enable_dkt(settings)
        predictor = build_predictor(session, settings)
        problem = _problem(session, "LC_E1")
        before = predictor.snapshot(uuid.uuid4())  # zero state, nothing attempted
        p_before = before.predict_success(problem)
        mastery_before = before.mastery()

        services.ingestion.ingest(event_request(user="U1", problem="LC_E1",
                                                result="WRONG_ANSWER", minutes_ago=30))
        services.ingestion.ingest(event_request(user="U1", problem="LC_M1", result="ACCEPTED",
                                                minutes_ago=20, hint_used=True))
        services.ingestion.ingest(event_request(user="U1", problem="LC_E1", result="ACCEPTED",
                                                attempt=2, minutes_ago=10))
        session.commit()

        after = predictor.snapshot(_learner_id(session, "U1"))
        assert after.events_replayed == 3
        p_after = after.predict_success(problem)
        assert p_after is not None and 0.0 <= p_after <= 1.0
        # the state moved AND LC_E1 now gets the rho retry term
        assert p_after != p_before
        assert after.mastery() != mastery_before

    def test_predict_success_none_without_known_concept(self, session, settings, mini_catalog):
        _enable_dkt(settings)
        predictor = build_predictor(session, settings)
        predictor.snapshot(uuid.uuid4())  # force the bulk feature load first

        alien = Concept(code="QUANTUM_COMPUTING", name="Quantum Computing")
        session.add(alien)
        session.flush()
        unknown = Problem(problem_key="LC_Q1", title="q",
                          static_difficulty=StaticDifficulty.EASY,
                          prior_difficulty=3.0, estimated_difficulty=3.0)
        untagged = Problem(problem_key="LC_NONE", title="n",
                           static_difficulty=StaticDifficulty.EASY,
                           prior_difficulty=3.0, estimated_difficulty=3.0)
        session.add_all([unknown, untagged])
        session.flush()
        session.add(ProblemConcept(problem_id=unknown.id, concept_id=alien.id, weight=1.0))
        session.commit()

        snap = predictor.snapshot(uuid.uuid4())
        assert snap.predict_success(unknown) is None   # concept the model does not know
        assert snap.predict_success(untagged) is None  # no concepts at all
        ghost = Problem(problem_key="GHOST", title="g",
                        static_difficulty=StaticDifficulty.EASY,
                        prior_difficulty=3.0, estimated_difficulty=3.0)
        ghost.id = uuid.uuid4()  # never persisted
        assert snap.predict_success(ghost) is None     # not in the catalog

    def test_problems_registered_later_are_loaded_lazily(self, session, settings, mini_catalog):
        _enable_dkt(settings)
        predictor = build_predictor(session, settings)
        predictor.snapshot(uuid.uuid4())  # the bulk load happens here
        late = Problem(problem_key="LC_LATE", title="late",
                       static_difficulty=StaticDifficulty.MEDIUM,
                       prior_difficulty=5.0, estimated_difficulty=5.0)
        session.add(late)
        session.flush()
        arrays = session.scalar(select(Concept).where(Concept.code == "ARRAYS"))
        session.add(ProblemConcept(problem_id=late.id, concept_id=arrays.id, weight=1.0))
        session.commit()

        snap = predictor.snapshot(uuid.uuid4())
        p = snap.predict_success(late)
        assert p is not None and 0.0 <= p <= 1.0


# --- UnavailableDktPredictor / build_predictor wiring (DktConfiguration) -----------


class TestUnavailableDktPredictor:
    def test_disabled_by_default(self, session, settings):
        predictor = build_predictor(session, settings)  # dkt.enabled defaults to False
        assert isinstance(predictor, UnavailableDktPredictor)
        assert not predictor.available()
        assert predictor.snapshot(uuid.uuid4()) is None
        assert (predictor.status()
                == "UNAVAILABLE (disabled by knowledge-tracer.dkt.enabled=false)")

    def test_disabled_never_touches_the_model_file(self, session, settings):
        settings.dkt.enabled = False
        settings.dkt.model_path = str(Path(__file__).parent / "_missing_model_.json")
        predictor = build_predictor(session, settings)
        assert isinstance(predictor, UnavailableDktPredictor)
        assert "disabled" in predictor.status()

    def test_missing_file_degrades_to_unavailable(self, session, settings):
        settings.dkt.enabled = True
        settings.dkt.model_path = str(Path(__file__).parent / "_missing_model_.json")
        predictor = build_predictor(session, settings)
        assert isinstance(predictor, UnavailableDktPredictor)
        assert "model file not found" in predictor.status()
        assert predictor.snapshot(uuid.uuid4()) is None

    def test_corrupt_file_degrades_to_unavailable(self, session, settings):
        bad = Path(__file__).parent / "_corrupt_model_tmp.json"
        bad.write_text("{ this is not json", encoding="utf-8")
        try:
            settings.dkt.enabled = True
            settings.dkt.model_path = str(bad)
            predictor = build_predictor(session, settings)
            assert isinstance(predictor, UnavailableDktPredictor)
            assert "invalid model file" in predictor.status()
        finally:
            bad.unlink(missing_ok=True)

    def test_directory_as_model_file_degrades_to_unavailable(self, session, settings):
        settings.dkt.enabled = True
        settings.dkt.model_path = str(Path(__file__).parent)
        predictor = build_predictor(session, settings)
        assert isinstance(predictor, UnavailableDktPredictor)
        assert "invalid model file" in predictor.status()
