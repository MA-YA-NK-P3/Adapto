"""kt-dkt-v1 feature encoding + reference forward pass (standard library only).

This file is the SPECIFICATION of the model contract shared by
  * model/dkt/dkt_model.py      (PyTorch training),
  * backend .../dkt/DktModel.java (live inference),
  * the Colab notebook           (inlined copy).
Any change here must bump FORMAT and be mirrored in Java (DktModelTest checks parity
against a fixture generated by model/dkt/make_fixture.py).

Input at step t (problem q_t, outcome y_t):
    x_t = [ w_t * y_t  (K) ,  w_t * (1 - y_t)  (K) ,  d_t ,  a_t ]            size 2K + 2
    w_t  catalog concept weights of q_t (primary = 1.0), zero for other concepts
    d_t  (priorDifficulty(q_t) - 5) / 2
    a_t  1 if a hint was used or the solution was viewed, else 0
Recurrence: one LSTM layer, PyTorch gate order (i, f, g, o), h_0 = c_0 = 0.
Concept head: y = W_out h + b_out                                          size K
Prediction for the NEXT attempt on problem q, from the state after t events:
    logit = (sum_k w_qk y_k) / (sum_k w_qk) - gamma * d_q - delta_q + rho * r_q + bias
    r_q      1 if the learner already attempted q before, else 0
    delta_q  learned per-problem difficulty offset ("itemOffsets"; 0 for unseen problems)
    p        = sigmoid(logit)
Concept mastery readout (first attempt, average difficulty): sigmoid(y_k + bias)
"""
import math
from typing import Dict, List, Sequence

FORMAT = "kt-dkt-v1"
DIFFICULTY_CENTER = 5.0
DIFFICULTY_SCALE = 2.0


def sigmoid(x: float) -> float:
    if x >= 0:
        return 1.0 / (1.0 + math.exp(-x))
    z = math.exp(x)
    return z / (1.0 + z)


def scaled_difficulty(prior: float) -> float:
    return (prior - DIFFICULTY_CENTER) / DIFFICULTY_SCALE


class Encoder:
    """Maps catalog problems to dense weight vectors over an ordered concept list."""

    def __init__(self, concepts: Sequence[str], problems: Sequence[dict]):
        self.concepts = list(concepts)
        self.index = {c: i for i, c in enumerate(self.concepts)}
        self.k = len(self.concepts)
        self.weights: Dict[str, List[float]] = {}
        self.difficulty: Dict[str, float] = {}
        for p in problems:
            w = [0.0] * self.k
            for c, v in p["conceptWeights"].items():
                if c in self.index:
                    w[self.index[c]] = float(v)
            self.weights[p["problemId"]] = w
            self.difficulty[p["problemId"]] = scaled_difficulty(float(p.get("priorDifficulty", 5.0)))

    @property
    def input_size(self) -> int:
        return 2 * self.k + 2

    def input_vector(self, problem_id: str, correct: int, assisted: int) -> List[float]:
        w = self.weights[problem_id]
        y = 1.0 if correct else 0.0
        return [v * y for v in w] + [v * (1.0 - y) for v in w] + [self.difficulty[problem_id], float(assisted)]


def assisted(event: dict) -> int:
    return 1 if (event.get("hintUsed") or event.get("solutionViewed")) else 0


class ReferenceDkt:
    """Pure-Python forward pass over exported kt-dkt-v1 weights (slow; for parity tests)."""

    def __init__(self, model: dict):
        if model.get("format") != FORMAT:
            raise ValueError(f"unsupported model format {model.get('format')!r}")
        self.concepts = model["concepts"]
        self.k = len(self.concepts)
        self.h = int(model["hiddenSize"])
        self.w_ih = model["weights"]["lstm.weight_ih"]
        self.w_hh = model["weights"]["lstm.weight_hh"]
        self.b = [a + b for a, b in zip(model["weights"]["lstm.bias_ih"], model["weights"]["lstm.bias_hh"])]
        self.w_out = model["weights"]["out.weight"]
        self.b_out = model["weights"]["out.bias"]
        self.gamma = float(model["weights"]["gamma"])
        self.rho = float(model["weights"]["rho"])
        self.bias = float(model["weights"]["bias"])
        self.item_offsets = {k: float(v) for k, v in model.get("itemOffsets", {}).items()}

    def initial_state(self):
        return [0.0] * self.h, [0.0] * self.h

    def step(self, state, x: Sequence[float]):
        h, c = state
        H = self.h
        gates = []
        for r in range(4 * H):
            s = self.b[r]
            row_i, row_h = self.w_ih[r], self.w_hh[r]
            for j, xv in enumerate(x):
                if xv:
                    s += row_i[j] * xv
            for j, hv in enumerate(h):
                s += row_h[j] * hv
            gates.append(s)
        new_c, new_h = [], []
        for u in range(H):
            i = sigmoid(gates[u])
            f = sigmoid(gates[H + u])
            g = math.tanh(gates[2 * H + u])
            o = sigmoid(gates[3 * H + u])
            cu = f * c[u] + i * g
            new_c.append(cu)
            new_h.append(o * math.tanh(cu))
        return new_h, new_c

    def concept_logits(self, state) -> List[float]:
        h = state[0]
        return [self.b_out[k] + sum(self.w_out[k][j] * h[j] for j in range(self.h)) for k in range(self.k)]

    def predict(self, state, weights: Sequence[float], difficulty: float, attempted: bool,
                problem_id: str = None) -> float:
        y = self.concept_logits(state)
        total = sum(weights)
        concept = sum(w * v for w, v in zip(weights, y)) / total if total > 0 else 0.0
        offset = self.item_offsets.get(problem_id, 0.0)
        return sigmoid(concept - self.gamma * difficulty - offset + (self.rho if attempted else 0.0) + self.bias)

    def mastery(self, state) -> List[float]:
        return [sigmoid(v + self.bias) for v in self.concept_logits(state)]
