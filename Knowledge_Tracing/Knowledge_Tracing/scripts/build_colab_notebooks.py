def execute(nb_path: pathlib.Path):
    """Execute all code cells in one interpreter (quick mode) — a smoke test of the notebook."""
    nb = json.loads(nb_path.read_text())
    src = "\n\n".join("".join(c["source"]) for c in nb["cells"] if c["cell_type"] == "code")
    with tempfile.TemporaryDirectory(dir=ROOT / "backend" / "target") as d:
        script = pathlib.Path(d) / (nb_path.stem + ".py")
        script.write_text("import matplotlib\nmatplotlib.use('Agg')\n" + src.replace("plt.show()", "plt.close('all')"))
        env = dict(os.environ, KT_QUICK="1", KT_WORKDIR=str(pathlib.Path(d) / "work"))
        proc = subprocess.run([sys.executable, str(script)], cwd=d, env=env, text=True,
                              stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    tail = "\n".join(proc.stdout.splitlines()[-25:])
    print(f"--- {nb_path.name}: exit {proc.returncode}\n{tail}")
    return proc.returncode == 0


